#!/usr/bin/env python3
"""
Generate C++ third/fourth-derivative code (d34) for the discrete EGPD families.

WHY THIS EXISTS
---------------
`.outer()` in R/setup_and_fit.R selects smoothing parameters by REML. It can use a
Newton iteration with analytic REML derivatives, but only when the family supplies
`d340`; setup_and_fit.R:521 silently demotes `outer` to "fd" (finite-difference BFGS)
otherwise. Every discrete family had `d340 = NULL`, so every discrete fit took the
finite-difference path -- and it does not work well. On lassa national (n = 84) with a
te() DLNM, three starting points reached negREML 1459.3, 714.1 and 738.1 while all
three reported convergence = 0, and the worst of them left all six log smoothing
parameters within 0.8 of their starting values. REML itself prefers the well-smoothed
fit (df 13.5, negREML 714.1); the optimiser simply could not find it, so a penalised
smooth came back with 78.8 of 116 coefficients unshrunk and an AIC 300 points below an
unpenalised crossbasis -- interpolation reported as fit.

COLUMN ORDER (must match .indices() in R/logdetH.R)
--------------------------------------------------
For nX parameters the output is nobs x (n3 + n4), third derivatives first, each block
in graded lexicographic order of the derivative multi-index. For nX = 3:

  cols 1-10  d3:  (3,0,0) (2,1,0) (2,0,1) (1,2,0) (1,1,1) (1,0,2)
                  (0,3,0) (0,2,1) (0,1,2) (0,0,3)
  cols 11-25 d4:  (4,0,0) (3,1,0) (3,0,1) (2,2,0) (2,1,1) (2,0,2) (1,3,0) (1,2,1)
                  (1,1,2) (1,0,3) (0,4,0) (0,3,1) (0,2,2) (0,1,3) (0,0,4)

verified against .indices(3)$i3 / $i4 by the 'indexcheck' target below.

USAGE
-----
    python derive_degpd_d34.py degpd1      > frag_degpd1_d34.cpp
    python derive_degpd_d34.py degpd1id    > frag_degpd1id_d34.cpp
    python derive_degpd_d34.py indexcheck  > check_order.R

Fragments are pasted into src/degpd.cpp; the R wrapper and the .*fns list entry are
updated by hand, and the result is checked against finite differences of d120 by
tests/testthat/test-d34-discrete.R.

The generated rational expressions lose precision near zero shape. The R wrappers
reject xi < 1e-3 (log link) or abs(xi) < 0.05 (identity link), and the outer solver
then retries with finite differences. Capped log links and compact fits also use
finite differences.
Use 'wrap' or 'wrapid' to emit a complete function, including support/zero branches.
"""

import sys
import itertools
import sympy as sp
from sympy import symbols, exp, log
from sympy import cse
try:                                     # sympy >= 1.8
    from sympy.printing.c import ccode
except ImportError:                      # older sympy, as derive_gradients.py assumes
    from sympy.printing.ccode import ccode

# ── parameters ────────────────────────────────────────────────────────
y = symbols('y', nonnegative=True)
lsigma, lxi, lkappa = symbols('lsigma lxi lkappa', real=True)
PARS = (lsigma, lxi, lkappa)


def multi_indices(nX, order):
    """Derivative multi-indices of a given order, graded lexicographic.

    combinations_with_replacement over parameter positions yields exactly the
    order baked into .indices(): for nX=3, order=3 this gives
    (3,0,0), (2,1,0), (2,0,1), (1,2,0), (1,1,1), (1,0,2), (0,3,0), ...
    """
    out = []
    for combo in itertools.combinations_with_replacement(range(nX), order):
        idx = [0] * nX
        for c in combo:
            idx[c] += 1
        out.append(tuple(idx))
    return out


def generate_index_check(nX=3):
    """Emit R asserting our column order equals .indices()'s, so a silent mismatch
    cannot survive. A wrong order would not error -- it would quietly corrupt the
    REML Hessian, which is exactly the failure this file exists to fix."""
    i3 = multi_indices(nX, 3)
    i4 = multi_indices(nX, 4)
    n3 = len(i3)
    return "\n".join([
        "## generated by derive_degpd_d34.py -- column order assertion",
        "ind <- egpd:::.indices(%d)" % nX,
        "mi <- function(...) { m <- integer(%d); for (z in c(...)) m[z] <- m[z] + 1L; m }" % nX,
        "ord3 <- list(%s)" % ", ".join("c(%s)" % ",".join(map(str, m)) for m in i3),
        "ord4 <- list(%s)" % ", ".join("c(%s)" % ",".join(map(str, m)) for m in i4),
        "for (i in 1:%d) for (j in 1:%d) for (k in 1:%d) {" % (nX, nX, nX),
        "  stopifnot(identical(as.integer(ord3[[ind$i3[i,j,k]]]), as.integer(mi(i,j,k))))",
        "  for (l in 1:%d)" % nX,
        "    stopifnot(identical(as.integer(ord4[[ind$i4[i,j,k,l] - %d]]), as.integer(mi(i,j,k,l))))" % n3,
        "}",
        'cat("column order matches .indices()\\n")'])


def degpd1_nll_endpoint(xi_identity=False):
    """Endpoint cell: xi < 0 puts the upper support endpoint below y+1, so H(y+1) = 1
    and F_hi = G(1) = 1 exactly. pmf = 1 - F_lo^kappa. degpd1d0/d12 already special-case
    this (src/degpd.cpp: `hi = 1.0;`), and d34 must branch identically or the REML
    Hessian would disagree with the gradient precisely on the bounded-tail fits that
    matter most here."""
    sigma = exp(lsigma)
    xi = lxi if xi_identity else exp(lxi)
    kappa = exp(lkappa)
    t_lo = 1 + xi * y / sigma
    F_lo = 1 - t_lo ** (-1 / xi)
    return -log(1 - F_lo ** kappa)


def degpd1_nll_zero(xi_identity=False):
    """y = 0 cell. H(0) = 0 exactly, so F_lo = 0 and pmf = F_hi^kappa.

    Taking the general expression to the limit instead of branching gives 0^(kappa-k)
    with k up to 4, i.e. NaN: caught by comparing d34 against finite differences of
    d12, which is finite at y = 0 because its own lower term drops out cleanly."""
    sigma = exp(lsigma)
    xi = lxi if xi_identity else exp(lxi)
    kappa = exp(lkappa)
    t_hi = 1 + xi / sigma
    F_hi = 1 - t_hi ** (-1 / xi)
    return -kappa * log(F_hi)


def degpd1_nll(xi_identity=False):
    """Negative log-pmf for DEGPD model 1 (carrier G(v) = v^kappa).

        H(x)   = 1 - (1 + xi*x/sigma)^(-1/xi)      GPD cdf
        F(x)   = G(H(x)) = H(x)^kappa
        pmf(y) = F(y+1) - F(y)

    The endpoint cell (t_hi <= 0, where H(y+1) = 1 so F_hi = 1) and the
    out-of-support cell (t_lo <= 0) are branches handled in the C++ wrapper, not
    here: they are not differentiable boundaries and carry their own penalty.
    """
    sigma = exp(lsigma)
    xi = lxi if xi_identity else exp(lxi)
    kappa = exp(lkappa)
    t_lo = 1 + xi * y / sigma
    t_hi = 1 + xi * (y + 1) / sigma
    F_lo = 1 - t_lo ** (-1 / xi)
    F_hi = 1 - t_hi ** (-1 / xi)
    pmf = F_hi ** kappa - F_lo ** kappa
    return -log(pmf)


# Cancellation guard. In the upper tail the generated forms take the cell
# probability as a difference of two numbers near 1 (F_lo^kappa - F_hi^kappa, or
# F_lo^kappa - 1 in the endpoint cell) and log F as log(1 - s); both lose
# eps/P relative accuracy (16% of the third derivatives at P ~ 1e-13). When the
# cell probability is below 1e-6 the CSE symbols equal to that difference and to
# log F_lo, log F_hi (found numerically below) are recomputed stably through
# helpers defined next to the generated functions in src/degpd.cpp; larger
# cells keep the plain forms bit for bit.
# The guard applies in the upper tail only, F_lo^kappa > 1/2 (degpd1_upper_tail;
# an endpoint cell with P < 1e-6 always is). Below it (e.g. H(y) small, or a
# large kappa) the difference does not cancel, and every plain symbol derives
# from the same rounding of s = t^(-1/xi), whose relative error eps*s/H the
# derivatives then absorb consistently; substituting values recomputed from
# another rounding of s broke the cancellation between their terms (fourth
# derivatives 255% off at H(y) = 1e-8).
def negpmf_guard(name):
    """(C++ lines opening the branch, [(target, C++ override, required), ...]) or None."""
    if name.endswith('_zero'):
        return None
    sigma = exp(lsigma)
    xi = lxi if name.startswith('degpd1id') else exp(lxi)
    kappa = exp(lkappa)
    F_lo = 1 - (1 + xi * y / sigma) ** (-1 / xi)
    if name.endswith('_endpoint'):
        init = ["const double negpmf_s = degpd1_negpmf_endpoint(t_lo, xi, exp(lkappa));",
                "const bool tiny_cell = negpmf_s > -1e-6;"]
        return init, [(F_lo ** kappa - 1, "negpmf_s", True),
                      (log(F_lo), "log1p(-exp(-log(t_lo) / xi))", False)]
    F_hi = 1 - (1 + xi * (y + 1) / sigma) ** (-1 / xi)
    init = ["const double negpmf_s = degpd1_negpmf(t_lo, xi, sigma, exp(lkappa));",
            "const bool tiny_cell = negpmf_s > -1e-6 && degpd1_upper_tail(t_lo, xi, exp(lkappa));"]
    return init, [(F_lo ** kappa - F_hi ** kappa, "negpmf_s", True),
                  (log(F_lo), "log1p(-exp(-log(t_lo) / xi))", False),
                  (log(F_hi), "log1p(-exp(-log(t_hi) / xi))", False)]


def find_cse_symbol(name, reps, target, required=True):
    """The CSE symbol whose value equals target at two generic points (or None)."""
    ident = name.startswith('degpd1id')
    points = [{y: sp.Rational(27, 10), lsigma: sp.Rational(3, 10),
               lxi: (sp.Rational(3, 10) if ident else log(sp.Rational(3, 10))),
               lkappa: sp.Rational(2, 5)},
              {y: sp.Rational(7, 1), lsigma: sp.Rational(-1, 5),
               lxi: (sp.Rational(9, 20) if ident else log(sp.Rational(9, 20))),
               lkappa: sp.Rational(-3, 10)}]
    hits = None
    for pt in points:
        vals = {}
        want = sp.N(target.subs(pt), 40)
        found = set()
        for s, e in reps:
            vals[s] = sp.N(e.subs(pt).subs(vals), 40)
            if abs(vals[s] - want) <= sp.Float('1e-30', 40) * abs(want):
                found.add(s)
        hits = found if hits is None else hits & found
    if len(hits) == 1:
        return hits.pop()
    if required or len(hits) > 1:
        sys.exit("%s: expected one CSE symbol for %s, found %r"
                 % (name, target, sorted(map(str, hits))))
    sys.stderr.write("%s: no CSE symbol for %s (not guarded)\n" % (name, target))
    return None


MODELS = {
    'degpd1':            lambda: degpd1_nll(xi_identity=False),
    'degpd1id':          lambda: degpd1_nll(xi_identity=True),
    'degpd1_endpoint':   lambda: degpd1_nll_endpoint(xi_identity=False),
    'degpd1id_endpoint': lambda: degpd1_nll_endpoint(xi_identity=True),
    'degpd1_zero':       lambda: degpd1_nll_zero(xi_identity=False),
    'degpd1id_zero':     lambda: degpd1_nll_zero(xi_identity=True),
}


def emit(name):
    nll = MODELS[name]()
    nX = len(PARS)
    i3 = multi_indices(nX, 3)
    i4 = multi_indices(nX, 4)

    exprs = []
    for m in i3 + i4:
        e = nll
        for p, k in zip(PARS, m):
            for _ in range(k):
                e = sp.diff(e, p)
        exprs.append(e)

    reps, reduced = cse(exprs, optimizations='basic')

    print("// ============================================================")
    print("// %s d34: third then fourth derivatives w.r.t. (lsigma, %s, lkappa)"
          % (name, 'xi' if name.startswith('degpd1id') else 'lxi'))
    print("// GENERATED by derive_degpd_d34.py -- do not edit by hand.")
    print("// %d third + %d fourth = %d columns, graded lex (see .indices())."
          % (len(i3), len(i4), len(i3) + len(i4)))
    print("// ============================================================")
    for symb, e in reps:
        print("double %s = %s;" % (symb, ccode(e)))
    for i, e in enumerate(reduced):
        m = (i3 + i4)[i]
        print("out(j, %d) = %s;   // d^%d (%s)"
              % (i, ccode(e), sum(m), ",".join(map(str, m))))


def emit_body(name, indent="      "):
    """The CSE block plus out() assignments for one branch, indented, no header."""
    nll = MODELS[name]()
    nX = len(PARS)
    order = multi_indices(nX, 3) + multi_indices(nX, 4)
    exprs = []
    for m in order:
        e = nll
        for p, k in zip(PARS, m):
            for _ in range(k):
                e = sp.diff(e, p)
        exprs.append(e)
    reps, reduced = cse(exprs, optimizations='basic')
    guard = negpmf_guard(name)
    lines, overrides = [], {}
    if guard:
        lines += ["%s%s" % (indent, l) for l in guard[0]]
        for target, cexpr, required in guard[1]:
            gs = find_cse_symbol(name, reps, target, required)
            if gs is not None:
                overrides[gs] = cexpr
    for s, e in reps:
        lines.append("%sdouble %s = %s;" % (indent, s, ccode(e)))
        if s in overrides:
            lines.append("%sif (tiny_cell) %s = %s;" % (indent, s, overrides[s]))
    lines += ["%sout(j, %d) = %s;" % (indent, i, ccode(e))
              for i, e in enumerate(reduced)]
    return "\n".join(lines)


def wrap(identity):
    """The whole C++ function, branch structure included.

    Branching must mirror degpd1d0/d12 exactly (src/degpd.cpp):
      t_lo <= 0  observation outside support -- d0 adds a penalty, which is constant
                 in the parameters, so all derivatives are zero here.
      t_hi <= 0  endpoint cell, F_hi = 1 (see degpd1_nll_endpoint).
      otherwise  interior cell.
    """
    fn = "degpd1id34" if identity else "degpd1d34"
    interior = 'degpd1id' if identity else 'degpd1'
    endpoint = interior + '_endpoint'
    zero = interior + '_zero'
    xisrc = ('if (std::abs(lxi) < 0.05)\n'
             '      Rcpp::stop("analytic DEGPD d34 is unstable near zero shape");\n'
             '    double xi = lxi;' if identity
             else "double xi = exp(bounded_lxi(lxi, xi_max, nullptr, nullptr));")
    print("// GENERATED by derive_degpd_d34.py (%s) -- do not edit by hand." % fn)
    print("// [[Rcpp::export]]")
    print("arma::mat %s(const Rcpp::List& pars, arma::mat X1, arma::mat X2, arma::mat X3," % fn)
    print("                  arma::vec yvec, const arma::uvec dupid, int dcate,")
    print("                  const Rcpp::List& offsets, double xi_max)")
    print("{")
    print("  arma::vec lsigmavec = X1 * Rcpp::as<arma::vec>(pars[0]);")
    print("  arma::vec lxivec    = X2 * Rcpp::as<arma::vec>(pars[1]);")
    print("  arma::vec lkappavec = X3 * Rcpp::as<arma::vec>(pars[2]);")
    print("  int nobs = yvec.size();")
    print("  arma::mat out = arma::mat(nobs, 25, arma::fill::zeros);")
    print("  if (dcate == 1) {")
    print("    lsigmavec = lsigmavec.elem(dupid);")
    print("    lxivec    = lxivec.elem(dupid);")
    print("    lkappavec = lkappavec.elem(dupid);")
    print("  }")
    print("  {")
    print("    arma::vec off0 = Rcpp::as<arma::vec>(offsets[0]);")
    print("    if (off0.n_elem > 0) lsigmavec += off0;")
    print("    arma::vec off1 = Rcpp::as<arma::vec>(offsets[1]);")
    print("    if (off1.n_elem > 0) lxivec += off1;")
    print("    arma::vec off2 = Rcpp::as<arma::vec>(offsets[2]);")
    print("    if (off2.n_elem > 0) lkappavec += off2;")
    print("  }")
    print("  for (int j = 0; j < nobs; j++) {")
    print("    double y      = yvec[j];")
    print("    double lsigma = lsigmavec[j];")
    print("    double lxi    = lxivec[j];")
    print("    double lkappa = lkappavec[j];")
    print("    %s" % xisrc)
    print("    double sigma  = exp(lsigma);")
    print("    double t_lo   = 1.0 + xi * y / sigma;")
    print("    double t_hi   = 1.0 + xi * (y + 1.0) / sigma;")
    print("    // out-of-support: d0 charges a constant penalty, so every derivative is 0")
    print("    if (t_lo <= 0.0) continue;")
    print("    // y = 0: F_lo = 0 exactly; the general form would give 0^(kappa-k) = NaN")
    print("    if (y <= 0.0) {")
    print(emit_body(zero))
    print("    } else if (t_hi <= 0.0) {")
    print(emit_body(endpoint))
    print("    } else {")
    print(emit_body(interior))
    print("    }")
    print("  }")
    print("  return out;")
    print("}")


if __name__ == '__main__':
    what = sys.argv[1] if len(sys.argv) > 1 else 'degpd1'
    if what == 'indexcheck':
        print(generate_index_check())
    elif what == 'wrap':
        wrap(identity=False)
    elif what == 'wrapid':
        wrap(identity=True)
    elif what in MODELS:
        emit(what)
    else:
        sys.exit("unknown model %r; choose from %s, 'wrap', 'wrapid' or 'indexcheck'"
                 % (what, ", ".join(MODELS)))
